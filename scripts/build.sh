#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
if [[ "$(wasm-bindgen --version)" != 'wasm-bindgen 0.2.104' ]]; then
  echo 'Install wasm-bindgen-cli 0.2.104 (see README).' >&2
  exit 1
fi
cargo build --locked --release --target wasm32-unknown-unknown
build_stage=$(mktemp -d)
trap 'rm -rf "$build_stage"' EXIT
wasm-bindgen target/wasm32-unknown-unknown/release/jrepas_web.wasm --target web --out-dir "$build_stage" --out-name jrepas --no-typescript
python3 - "$build_stage" <<'PY'
from pathlib import Path
import hashlib, shutil, sys
stage = Path(sys.argv[1])
files = sorted(stage.glob('*'))
revision = hashlib.sha256(b''.join(p.read_bytes() for p in files)).hexdigest()[:12]
destination = Path('assets/rust') / revision
destination.mkdir(parents=True, exist_ok=True)
for file in files:
    shutil.copy2(file, destination / file.name)
Path('site.js').write_text(f'''// Generated by scripts/build.sh. Application logic is in src/lib.rs.
import init from './assets/rust/{revision}/jrepas.js';
init().then(() => import('./motion.js?v=10')).catch(error => console.error('Unable to start the application:', error));
''')
print(f'Built Rust/WebAssembly assets: {destination}')
PY
